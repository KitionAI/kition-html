#!/usr/bin/env python3
"""Generate deterministic, host-independent grayscale glyph coverage tables.

The renderer's existing outline profile approximates black CoreText masks.
Invert the black sRGB preblend, then apply Skia's foreground-dependent preblend.
The macOS non-LCD color reduction is applied separately by glyph_gamma.rs.
This does not reproduce CoreText outline dilation or its scan conversion.
"""

import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "vendor/vello_cpu/src/glyph_gamma_tables.rs"
HEADER = """// Copyright 2012 Google Inc.
// Adapted preblend arithmetic: see ../LICENSE.skia.
// Generated by tools/generate-glyph-coverage.py. Do not edit by hand.
// Skia source: fd139e79fd4553ba16556c1bca6c0f4dd9bc6fa5, src/core/SkMaskGamma.cpp.
#[rustfmt::skip]
const TABLES: [[u8; 256]; 4] = [
"""


def linear(value):
    return value / 12.92 if value <= 0.04045 else ((value + 0.055) / 1.055) ** 2.4


def srgb(value):
    return 12.92 * value if value <= 0.0031308 else 1.055 * value ** (1 / 2.4) - 0.055


def generate():
    rows = []
    for index in range(4):
        source = ((index << 5) | (index << 2) | (index >> 1)) / 255
        destination = 1 - source
        row = []
        for value in range(256):
            coverage = 1 - linear(1 - value / 255)
            output = srgb(linear(source) * coverage + linear(destination) * (1 - coverage))
            corrected = (output - destination) / (source - destination)
            row.append(max(0, min(255, math.floor(255 * corrected + 0.5))))
        assert row[0] == 0 and row[-1] == 255
        assert all(a <= b for a, b in zip(row, row[1:]))
        if index == 0:
            assert row == list(range(256))
        rows.append("    [\n" + "".join(
            "        " + ", ".join(map(str, row[start:start + 16])) + ",\n"
            for start in range(0, 256, 16)
        ) + "    ],\n")
    return HEADER + "".join(rows) + "];\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the checked-in table")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if OUTPUT.read_text() != expected:
            raise SystemExit("Glyph coverage tables are stale; regenerate them.")
        print("Glyph coverage tables match the generator.")
    else:
        OUTPUT.write_text(expected)
        print("Generated vendor/vello_cpu/src/glyph_gamma_tables.rs")


if __name__ == "__main__":
    main()
